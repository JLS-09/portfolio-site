const SECTIONS = ["home", "about", "projects", "contact"] as const;
type Section = typeof SECTIONS[number];

export default function NavBar() {
  const [active, setActive] = useState<Section>("home");

  useEffect(() => {
    const observers: IntersectionObserver[] = [];

    SECTIONS.forEach((id) => {
      const el = document.getElementById(id);
      if (!el) return;

      const observer = new IntersectionObserver(
        ([entry]) => {
          if (entry.isIntersecting) setActive(id);
        },
        { rootMargin: "-40% 0px -55% 0px" }
      );

      observer.observe(el);
      observers.push(observer);
    });

    return () => observers.forEach((o) => o.disconnect());
  }, []);

  const btn = (id: Section) =>
    `${styles.navBtn}${active === id ? ` ${styles.navBtnActive}` : ""}`;

  return (
    <nav className={styles.nav}>
      <div className={styles.navPill}>
        <a href="#home" className={btn("home")} title="Home">
          <IconHome />
        </a>
        <a href="#about" className={btn("about")} title="About">
          <IconPerson />
        </a>
        <a href="#projects" className={btn("projects")} title="Projects">
          <IconGrid />
        </a>
        <a href="#contact" className={btn("contact")} title="Contact">
          <IconMail />
        </a>
        <span className={styles.navDivider} />
        <a href="https://www.linkedin.com/in/jules-van-nevel-39bbb1331/" target="_blank" rel="noopener noreferrer" className={styles.navBtn} title="LinkedIn">
          <IconLinkedIn />
        </a>
        <a href="https://github.com/JLS-09" target="_blank" rel="noopener noreferrer" className={styles.navBtn} title="GitHub">
          <IconGitHub />
        </a>
      </div>
    </nav>
  );
}
